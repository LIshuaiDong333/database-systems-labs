#include "stdafx.h"
#include "cmath"

void Rotate(POINT p0, POINT p1, POINT p2, POINT& p3)
{
	p3.x = 0;
	p3.y = 0;

	double a = p2.y * p1.x * p0.x + p2.y * p1.y * p0.y + p2.x * p1.y * p0.x - p2.x * p1.x * p0.y;
	double b = p2.x * p1.x * p0.x + p2.x * p1.y * p0.y + p2.y * p1.x * p0.y - p2.y * p1.y * p0.x;
	double deno = sqrt(a * a + b * b);
	if (deno == 0.0)
		return;
	double l0 = sqrt(p0.x * p0.x + p0.y * p0.y);
	if (l0 == 0.0)
		return;
	double l1 = sqrt(p1.x * p1.x + p1.y * p1.y);
	double l2 = sqrt(p2.x * p2.x + p2.y * p2.y);
	double l3 = l2 * l1 / l0;
	p3.x = int(l3 * b / deno);
	p3.y = int(l3 * a / deno);
}
